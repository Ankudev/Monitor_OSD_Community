const assert = require('node:assert/strict');
const {results, validMapPoint, locationWarning} = require('../tools/audit_map_render.cjs');
const cases = Object.fromEntries(results.map(result => [result.case,result]));
for (const name of ['missing_object_gps','null_event_point','empty_event_point','incomplete_event_point','out_of_range','boolean_point']) {
  assert.deepEqual(cases[name].drawn, [], name);
}
