const assert = require('node:assert/strict');
const fs = require('node:fs');
const source = fs.readFileSync('web/script.js', 'utf8');
const start = source.indexOf('function sourceClockState(');
const stop = source.indexOf('\nfunction ', start + 1);
const clock = new Function('formatDate', `${source.slice(start, stop)}; return sourceClockState;`)((value) => value);
const now = Date.parse('2026-10-05T18:00:00Z');
const health = { next_scan_at: '2026-10-05T19:02:03Z' };
assert.equal(clock(health, now, true).countdown, 'Za: 1 godz. 2 min 3 s');
assert.equal(clock(health, now + 2000, true).countdown, 'Za: 1 godz. 2 min 1 s');
assert.equal(clock(health, now, true).time, health.next_scan_at);
assert.equal(clock({ ...health, running: true }, now, true).time, 'Odczyt trwa');
assert.equal(clock(health, now, false).time, 'Termin niepotwierdzony');
assert.equal(clock({ ...health, running: true }, now, false).time, 'Termin niepotwierdzony');
assert.equal(clock({}, now, true).time, 'Oczekuje na pierwszy odczyt');
assert.equal(clock({ next_scan_at: 'invalid' }, now, true).time, 'Oczekuje na pierwszy odczyt');
assert.equal(clock(health, Date.parse(health.next_scan_at), true).time, 'Oczekuje na rozpoczęcie');
assert.equal(clock(health, now + 9999999, true).time, 'Oczekuje na rozpoczęcie');
assert.match(clock({ ...health, error: 'timeout' }, now, true).countdown, /^Ponowna próba:/);
assert.match(clock({ ...health, blocked_until: health.next_scan_at }, now, true).countdown, /^Przerwa wskazana przez operatora:/);
assert.equal(clock({ ...health, blocked_until: '2026-10-04T00:00:00Z' }, now, true).countdown, 'Za: 1 godz. 2 min 3 s');
assert.equal(clock({ next_scan_at: '2026-10-05T18:00:00.100Z' }, now, true).countdown, 'Za: 0 min 1 s');
const fullStart = source.indexOf('function fullScanClockState(');
const fullStop = source.indexOf('\nfunction ', fullStart + 1);
const full = new Function('sourceClockState', `${source.slice(fullStart, fullStop)}; return fullScanClockState;`)(clock);
const aligned = [health, { next_scan_at: '2026-10-05T19:02:04Z' }];
assert.equal(full(aligned, now, true).label, 'Następny pełny skan');
assert.equal(full(aligned, now, true).time, '2026-10-05T19:02:04Z');
assert.equal(full(aligned, now, true).countdown, 'Za: 1 godz. 2 min 4 s');
assert.equal(full(aligned, now, false).time, 'Termin niepotwierdzony');
assert.equal(full([], now, true).time, 'Brak aktywnych źródeł');
assert.equal(full([health, {}], now, true).time, 'Termin niepotwierdzony');
assert.equal(full([health, { ...health, running: true }], now, true).time, 'Odczyt trwa');
assert.equal(full(aligned, Date.parse(health.next_scan_at), true).time, 'Oczekuje na rozpoczęcie');
const postponed = full([health, { next_scan_at: '2026-10-05T23:00:00Z', error: 'timeout' }], now, true);
assert.equal(postponed.label, 'Najbliższy odczyt API');
assert.equal(postponed.time, health.next_scan_at);
assert.match(postponed.countdown, /terminy operatorów są różne/);
const mappingStart = source.indexOf('function applyMapPayload(');
const mappingStop = source.indexOf('\nasync function ', mappingStart);
const apply = new Function('describeDataStatus', `let geometries, objects, events, statusPayload; const adminCsrf = ''; ${source.slice(mappingStart, mappingStop)}; return (payload) => { applyMapPayload(payload); return statusPayload; };`)(() => ({}));
const payload = { locations: [], events: [], sources: ['pge','tauron','energa','enea','stoen'].map(source => ({ source, status: 'fresh', next_scan_at: health.next_scan_at })) };
const mapped = apply(payload);
assert.deepEqual(mapped.enabled_sources, ['pge','tauron','energa','enea','stoen']);
assert.equal(mapped.sources.pge.next_scan_at, health.next_scan_at);
assert.deepEqual(apply({ ...payload, sources: [payload.sources[0]] }).enabled_sources, ['pge']);
console.log('Zegary źródeł: odliczanie, błędy, przerwy i niepotwierdzony stan — OK.');
